// Render the code-native logo with the actual font, preserving the supplied
// raster artwork inside a traced SVG silhouette. No runtime renderer is needed.
import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const root = fileURLToPath(new URL("../", import.meta.url));
const out = `${root}public/brand`;
await mkdir(out, { recursive: true });
const source = (await readFile(`${root}brand/source.png`)).toString("base64");
const font = (await readFile(`${root}brand/space-grotesk-latin.woff2`)).toString("base64");
const silhouette = `
  <path d="M299 635V226C299 164 352 113 419 113V499H533V635Z"/>
  <path d="M446 241V225C446 162 499 113 576 113C710 113 797 217 797 369C797 480 739 575 649 626V457C692 409 689 317 635 268C618 251 595 241 576 241Z"/>
  <path d="M684 115L832 114C940 114 1039 184 1058 293H923C901 259 875 241 835 241H795C773 183 734 145 684 115Z"/>
  <path d="M934 318H1062L1066 351H942Z M942 375H1066L1062 410H936Z"/>
  <path d="M926 437H1060C1039 554 941 635 832 635H649V626C700 586 742 544 765 499H835C875 499 900 474 926 437Z"/>
  <path d="M532 266H546C614 261 649 296 649 359V635H532Z"/>`;

function mark(monochrome = false) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="291 105 783 538" aria-hidden="true"><defs><clipPath id="symbol">${silhouette}</clipPath></defs>${monochrome ? `<g fill="white">${silhouette}</g>` : `<image width="1254" height="1254" href="data:image/png;base64,${source}" clip-path="url(#symbol)"/>`}</svg>`;
}
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  async function render(name, width, height, content, style = "") {
    await page.setViewportSize({ width, height });
    await page.setContent(`<style>@font-face{font-family:Brand;src:url(data:font/woff2;base64,${font})}*{box-sizing:border-box}body{margin:0}#logo{width:${width}px;height:${height}px;display:flex;align-items:center;justify-content:center;${style}}svg{display:block;width:100%;height:100%}.word{font:700 112px/1 Brand;letter-spacing:-4px;white-space:nowrap}.gold{color:#bc8517;background:linear-gradient(120deg,#9d6103,#efb932,#a56b07);background-clip:text;-webkit-text-fill-color:transparent}.blue{color:#172878;background:linear-gradient(120deg,#0c145f,#1955d7);background-clip:text;-webkit-text-fill-color:transparent}</style><div id="logo">${content}</div>`);
    await page.evaluate(() => document.fonts.ready);
    await page.locator("#logo").screenshot({ path: `${out}/${name}.png`, omitBackground: true });
  }
  const word = '<span class="word"><span class="gold">Dhana</span><span class="blue">dhara</span></span>';
  await render("logo-horizontal", 960, 176, `<div style="width:224px;height:154px;flex-shrink:0">${mark()}</div>${word}`, "gap:24px");
  await render("logo-stacked", 960, 850, `<div style="width:760px;height:530px">${mark()}</div>${word}`, "flex-direction:column;gap:48px");
  await render("symbol", 783, 538, mark());
  for (const size of [32, 180, 192, 512]) {
    await render(`icon-${size}`, size, size, `<div style="width:88%;height:88%">${mark()}</div>`, "background:white;border-radius:15%");
  }
  await render("push-badge-96", 96, 96, mark(true));
  await render("social", 1200, 630, `<div style="width:360px;height:248px">${mark()}</div>${word}`, "flex-direction:column;gap:40px;background:#f3f3ee");
  await copyFile(`${out}/social.png`, `${root}app/opengraph-image.png`);
  await mkdir(`${root}../api/app/assets`, { recursive: true });
  await copyFile(`${out}/logo-horizontal.png`, `${root}../api/app/assets/logo-horizontal.png`);
  await copyFile(`${out}/icon-192.png`, `${root}public/icons/push-icon-192.png`);
  await copyFile(`${out}/push-badge-96.png`, `${root}public/icons/push-badge-96.png`);
  await writeFile(`${out}/README.md`, "# Dhanadhara brand assets\n\nGenerated by `node scripts/generate-brand-assets.mjs` from the user-supplied artwork and Space Grotesk. No tagline. Do not independently edit the API copy; the generator synchronizes it. Source and font license live in `apps/web/brand`.\n");
} finally {
  await browser.close();
}
